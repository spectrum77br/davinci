def upgrade() -> None:
    conn = op.get_bind()
    # Idempotência: skip se já existe alguma variation (seed já rodado).
    existing = conn.execute(text(
        f"SELECT 1 FROM {SCHEMA}.import_kit_variations LIMIT 1"
    )).first()
    if existing is not None:
        return

    # 1) Variations
    var_id_by_ordem: dict[int, str] = {}
    var_rows = []
    for ordem, code, highlight, obs in VARIATIONS:
        vid = str(uuid4())
        var_id_by_ordem[ordem] = vid
        var_rows.append({
            "id": vid, "code": code, "label": code,
            "ordem": ordem, "highlight": highlight, "obs": obs,
        })
    conn.execute(
        text(f"""
            INSERT INTO {SCHEMA}.import_kit_variations
                (id, code, label, ordem, highlight, obs)
            VALUES (:id, :code, :label, :ordem, :highlight, :obs)
        """),
        var_rows,
    )

    # 2) Bases
    base_id_by_sku: dict[str, str] = {}
    base_rows = []
    for ordem, modelo_bling, sku_base, cor in BASES:
        bid = str(uuid4())
        base_id_by_sku[sku_base] = bid
        base_rows.append({
            "id": bid, "modelo_bling": modelo_bling,
            "sku_base": sku_base, "cor": cor, "ordem": ordem,
        })
    conn.execute(
        text(f"""
            INSERT INTO {SCHEMA}.import_kit_bases
                (id, modelo_bling, sku_base, cor, ordem)
            VALUES (:id, :modelo_bling, :sku_base, :cor, :ordem)
        """),
        base_rows,
    )

    # 3) Marks — só linhas válidas (sku_base + variation_ordem existentes).
    mark_rows = []
    for sku_base, var_ordem in MARKS:
        bid = base_id_by_sku.get(sku_base)
        vid = var_id_by_ordem.get(var_ordem)
        if not bid or not vid:
            continue
        mark_rows.append({"id": str(uuid4()), "base_id": bid, "variation_id": vid})
    if mark_rows:
        conn.execute(
            text(f"""
                INSERT INTO {SCHEMA}.import_kit_marks (id, base_id, variation_id)
                VALUES (:id, :base_id, :variation_id)
            """),
            mark_rows,
        )


